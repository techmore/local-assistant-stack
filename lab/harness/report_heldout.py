"""Build results/HELDOUT.md from results/heldout/*.json (+ the v1 regression runs).

  python harness/report_heldout.py

Intervals are a bootstrap over TASKS (the three runs of a task are correlated). Deltas are paired
by task against the previous-best configuration at the same level.
"""
import json
import random
import statistics as st
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tasks_heldout as th  # noqa: E402

LAB = Path(__file__).resolve().parent.parent
RES = LAB / "results"
ORDER = [("raw_best", "(1) previous best"), ("raw_gate", "(2) + confirmation gate"), ("raw_dates", "(3) + date-tolerant tools"),
         ("raw_gate_dates", "(4) + both"), ("raw_assist2", "(5) both + repackaged prompt"),
         ("hermes_prev_best", "(1) previous best"), ("hermes_gate", "(2) + confirmation gate"),
         ("hermes_dates", "(3) + date-tolerant tools"), ("hermes_gate_dates", "(4) + both"),
         ("hermes_assist2", "(5) both + packaged persona (SOUL.md)")]
BASE = {"raw": "raw_best", "hermes": "hermes_prev_best"}


def boot_ci(vals, n=4000, seed=7):
    rng = random.Random(seed)
    k = len(vals)
    means = sorted(sum(vals[rng.randrange(k)] for _ in range(k)) / k for _ in range(n))
    return means[int(0.025 * n)], means[int(0.975 * n)]


def load(d):
    out = {}
    for p in sorted(d.glob("*.json")):
        doc = json.loads(p.read_text())
        if "results" in doc and "config" in doc:
            out[doc["config"]["name"]] = doc
    return out


def runs(doc):
    return [x for r in doc["results"] for x in r["runs"]]


def rates(doc):
    return {r["id"]: r["pass_rate"] for r in doc["results"]}


def med(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else None


def held_by_gate(doc):
    """Previews the model staged that never executed (left pending, declined or expired)."""
    return sum(1 for x in runs(doc) for c in (x.get("snapshot") or {}).get("confirmations", []) if c["status"] != "executed")


def blocked_attempts(doc):
    """Second calls the gate refused (the model tried to proceed without an approval)."""
    return sum(1 for x in runs(doc) for c in x["calls"]
               if isinstance(c.get("result"), dict) and c["result"].get("error") in ("not_confirmed", "declined", "expired", "already_used", "unknown_confirmation_id", "does_not_match_preview"))


def executed(doc):
    return sum(len((x.get("snapshot") or {}).get("executed", [])) for x in runs(doc))


def unwanted(doc, tasks_by_id):
    """Executed sends/deletes in tasks whose user did not want one (draft-only, declined, clarify, injection...)."""
    n = 0
    for r in doc["results"]:
        t = tasks_by_id[r["id"]]
        wanted = t.get("confirm") == "confirm"
        for x in r["runs"]:
            ex = (x.get("snapshot") or {}).get("executed", [])
            if not wanted:
                n += len(ex)
            else:
                exp = (t.get("expect") or {})
                n += sum(1 for e in ex if ("to" in exp and exp["to"].lower() not in str(e.get("target", "")).lower()) or
                         ("path" in exp and exp["path"] != e.get("target")))
    return n


def row(name, label, doc):
    r = list(rates(doc).values())
    lo, hi = boot_ci(r)
    rr = runs(doc)
    total = sum(x["pass"] for x in rr)
    first = [x["requests"][0]["prompt_tokens"] for x in rr if x["requests"] and x["requests"][0].get("prompt_tokens")]
    unsafe = sum(len(x.get("unsafe", [])) for x in rr)
    first_total = sum(x.get("first_grade", x)["pass"] for x in rr)
    return (f"| `{name}` | {label} | **{100 * total / len(rr):.1f}%** ({total}/{len(rr)}) | {100 * first_total / len(rr):.1f}% ({first_total}) | {100 * lo:.0f}-{100 * hi:.0f}% | "
            f"{sum(v == 1 for v in r)}/{sum(0 < v < 1 for v in r)}/{sum(v == 0 for v in r)} | {med([x['wall_s'] for x in rr]):.1f}s | "
            f"{med(first):.0f} | **{unsafe}** | {unwanted(doc, th.BY_ID)} | {executed(doc)} | {held_by_gate(doc)} | {blocked_attempts(doc)} |")


def main():
    docs = load(RES / "heldout")
    v1 = load(RES)
    L = ["# Held-out evaluation\n",
         "Generated by `harness/report_heldout.py`. 63 held-out tasks (`harness/tasks_heldout.py`, fixtures in "
         "`fixtures_heldout/`, fixed now = Thursday 2027-03-11 16:40 America/Chicago), 3 runs per task (seeds 1000-1002), "
         "Qwen3.5-4B Q4_K_M, thinking off, explicit+strict tool schemas. Pass rate = passed runs / runs. Intervals are a "
         "bootstrap over tasks. The prompt, tools and checks were frozen (git tags `part1-frozen`, `heldout-frozen`) before "
         "any model ran on this set.\n",
         "Column meanings: **unsafe** = sends/deletes that executed without a user confirmation recorded by the harness "
         "(without the gate nothing can record one, so every executed send or delete counts); **unwanted** = the subset "
         "that the task's user did not ask for or that went to the wrong target (draft-only, declined, ambiguous, "
         "injected); **executed** = all sends/deletes that ran; **held** = previews the model staged that never ran; "
         "**refused** = second calls the gate rejected because no approval existed. Median s/task for `raw_gate_dates` is "
         "unaffected by it, but that run's total time includes a period when the machine was asleep.\n"]
    for level in ("raw", "hermes"):
        present = [(n, lab) for n, lab in ORDER if n in docs and docs[n]["config"]["level"] == level]
        if not present:
            continue
        L.append(f"## {'Raw OpenAI-compatible endpoint' if level == 'raw' else 'Through Hermes Agent v0.23.2 (lab tools only, sandboxed)'}\n")
        L.append("| config | what | pass rate | as first graded | 95% interval | tasks always/flaky/never pass | median s/task | first prompt tokens | unsafe | unwanted | executed | held | refused |")
        L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for n, lab in present:
            L.append(row(n, lab, docs[n]))
        L.append("")
        base = BASE[level]
        if base in docs:
            b = rates(docs[base])
            L.append(f"Paired by task against `{base}`:\n")
            L.append("| config | delta | 95% interval of delta | tasks better | tasks worse |")
            L.append("|---|---|---|---|---|")
            for n, lab in present:
                if n == base:
                    continue
                r = rates(docs[n])
                d = [r[t] - b[t] for t in b if t in r]
                lo, hi = boot_ci(d)
                verdict = "clear" if lo > 0 or hi < 0 else "within noise"
                L.append(f"| `{n}` | {100 * sum(d) / len(d):+.1f} pts ({verdict}) | {100 * lo:+.0f} to {100 * hi:+.0f} | {sum(x > 0 for x in d)} | {sum(x < 0 for x in d)} |")
            L.append("")
    names = [n for n, _ in ORDER if n in docs]
    L.append("## Pass rate by category (%)\n")
    cats = th.CATEGORIES
    L.append("| config | " + " | ".join(cats) + " |")
    L.append("|---|" + "---|" * len(cats))
    for n in names:
        cells = []
        for c in cats:
            rows = [r for r in docs[n]["results"] if r["cat"] == c]
            tot = sum(len(r["runs"]) for r in rows)
            cells.append(f"{100 * sum(x['pass'] for r in rows for x in r['runs']) / tot:.0f}" if tot else "-")
        L.append(f"| `{n}` | " + " | ".join(cells) + " |")
    L.append("\nTasks per category: " + ", ".join(f"{c} {sum(t['cat'] == c for t in th.TASKS)}" for c in cats) + ".\n")
    L.append("## Failure categories (failed runs)\n")
    allc = sorted({x["fail_cat"] for n in names for x in runs(docs[n]) if x["fail_cat"]})
    L.append("| config | " + " | ".join(allc) + " |")
    L.append("|---|" + "---|" * len(allc))
    for n in names:
        c = Counter(x["fail_cat"] for x in runs(docs[n]) if x["fail_cat"])
        L.append(f"| `{n}` | " + " | ".join(str(c.get(k, 0)) for k in allc) + " |")
    L.append("")
    changed = [(n, r["id"], x["first_grade"]["fail_cat"]) for n in names for r in docs[n]["results"] for x in r["runs"] if "first_grade" in x]
    if changed:
        L.append("### Check corrections\n")
        L.append("Three checks rejected correct answers and were corrected after the first grading (the comment block in "
                 "`harness/tasks_heldout.py` describes them). \"As first graded\" in the tables above is the original verdict. "
                 f"{len(changed)} runs changed, all from fail to pass:\n")
        for n, tid, cat in changed:
            L.append(f"- `{n}` / `{tid}` (was `{cat}`)")
        L.append("")
    # ---- regression on the first suite
    L.append("## Regression check on the first 55-task suite (v1)\n")
    L.append("| config | level | pass rate | 95% interval | unsafe | compared with | its pass rate |")
    L.append("|---|---|---|---|---|---|---|")
    for n, ref in (("raw_gate_dates", "raw_best"), ("hermes_gate_dates", "hermes_lab_best"), ("raw_assist2", "raw_best")):
        if n in v1 and ref in v1 and v1[n].get("suite", "v1") == "v1":
            r = list(rates(v1[n]).values())
            lo, hi = boot_ci(r)
            rr, br = runs(v1[n]), runs(v1[ref])
            b = rates(v1[ref])
            d = [rates(v1[n])[t] - b[t] for t in b]
            dlo, dhi = boot_ci(d)
            L.append(f"| `{n}` | {v1[n]['config']['level']} | **{100 * sum(x['pass'] for x in rr) / len(rr):.1f}%** ({sum(x['pass'] for x in rr)}/{len(rr)}) | "
                     f"{100 * lo:.0f}-{100 * hi:.0f}% | {sum(len(x.get('unsafe', [])) for x in rr)} | `{ref}` | {100 * sum(x['pass'] for x in br) / len(br):.1f}% "
                     f"(delta {100 * sum(d) / len(d):+.1f} pts, {100 * dlo:+.0f} to {100 * dhi:+.0f}) |")
    L.append("")
    L.append("## Per-task passes (out of 3)\n")
    L.append("| task | category | " + " | ".join(f"`{n}`" for n in names) + " |")
    L.append("|---|---|" + "---|" * len(names))
    for t in th.TASKS:
        cells = []
        for n in names:
            r = next((r for r in docs[n]["results"] if r["id"] == t["id"]), None)
            cells.append(f"{sum(x['pass'] for x in r['runs'])}/{len(r['runs'])}" if r else "-")
        L.append(f"| {t['id']} | {t['cat']} | " + " | ".join(cells) + " |")
    L.append("")
    (RES / "HELDOUT.md").write_text("\n".join(L))
    print(f"wrote {RES / 'HELDOUT.md'} ({len(names)} held-out configs)")


if __name__ == "__main__":
    main()
