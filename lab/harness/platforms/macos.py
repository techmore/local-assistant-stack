"""macOS sandbox: sandbox-exec with a generated profile. Used for every Hermes process in this lab.

Two modes:
  guard  installing and manual use: deny writes to the user's own Hermes install, PATH wrappers,
         launchd agents and shell profiles; deny any access to other agents' login stores
  eval   every evaluation run (a 4B model is steering an agent): writes only to the lab's Hermes home
         and run/, no reads in the home directory outside the lab, loopback-only network minus every
         loopback port another local service was listening on, no Apple Events, no signals to other
         processes, no exec of automation / exfiltration binaries
Profiles are generated into <lab>/run/ at run time from the current home directory: nothing with a
user name or absolute path is kept in the repository.
"""
import os
import re
import shutil
import subprocess
from pathlib import Path

LAB_PORTS = {"18431", "18432"}
NO_EXEC = ["/usr/bin/osascript", "/usr/bin/osacompile", "/usr/bin/open", "/usr/bin/pbpaste", "/usr/bin/pbcopy",
           "/usr/sbin/screencapture", "/usr/bin/say", "/usr/bin/shortcuts", "/usr/bin/automator",
           "/usr/bin/security", "/usr/bin/ssh", "/usr/bin/scp", "/usr/bin/sftp", "/usr/bin/tccutil", "/usr/bin/defaults",
           "/usr/bin/mdfind", "/usr/bin/mdls", "/usr/bin/killall", "/usr/bin/pkill", "/usr/bin/sudo", "/usr/bin/crontab",
           "/usr/bin/at", "/usr/sbin/networksetup", "/usr/bin/sqlite3"]
NO_EXEC_NAMES = ["imsg", "brew", "gh", "claude", "codex", "opencode"]  # looked up on PATH, wherever the package manager put them


def available():
    if not shutil.which("sandbox-exec"):
        return False, "sandbox-exec not found"
    return True, ""


def guard_profile(home):
    return f"""(version 1)
(allow default)
; generated by harness/platforms/macos.py - do not edit by hand
(deny file-write*
  (subpath "{home}/.hermes")
  (subpath "{home}/.local/bin")
  (subpath "{home}/Library/LaunchAgents")
  (literal "{home}/.zshrc")
  (literal "{home}/.zprofile")
  (literal "{home}/.zshenv")
  (literal "{home}/.bashrc")
  (literal "{home}/.bash_profile")
  (literal "{home}/.profile"))
(deny file-read* file-write*
  (subpath "{home}/.codex")
  (subpath "{home}/.claude")
  (literal "{home}/.claude.json"))
"""


def _foreign_loopback_ports(lab):
    ports = set()
    out = subprocess.run(["lsof", "-nP", "-iTCP", "-sTCP:LISTEN"], capture_output=True, text=True).stdout
    for line in out.splitlines()[1:]:
        cols = line.split()
        m = re.search(r":(\d+)$", cols[8]) if len(cols) > 8 else None
        if m and m.group(1) not in LAB_PORTS and str(lab) not in subprocess.run(
                ["ps", "-o", "command=", "-p", cols[1]], capture_output=True, text=True).stdout:
            ports.add(m.group(1))
    return sorted(ports, key=int)


def eval_profile(home, lab):
    ports = _foreign_loopback_ports(lab)
    no_exec = set(NO_EXEC)
    for n in NO_EXEC_NAMES:
        p = shutil.which(n)
        if p:
            no_exec.add(p)
    no_exec = sorted(no_exec | {os.path.realpath(p) for p in no_exec if os.path.exists(p)})
    nl = "\n"
    cua = sorted(str(p) for p in (Path(lab) / "hermes-home" / "tools").glob("cua-driver-*")) if (Path(lab) / "hermes-home" / "tools").exists() else []
    return f"""(version 1)
(allow default)
; generated by harness/platforms/macos.py - do not edit by hand

; --- writes: lab state only
(deny file-write*)
(allow file-write*
  (subpath "{lab}/hermes-home") (subpath "{lab}/run")
  (subpath "/private/var/folders") (subpath "/private/tmp") (subpath "/dev"))

; --- reads: nothing personal
(deny file-read* (subpath "{home}") (subpath "/Volumes") (subpath "{Path(home).parent}/Shared"))
(allow file-read* (subpath "{lab}"))
(allow file-read-metadata (literal "{home}") (literal "{Path(lab).parent}") (literal "{Path(home).parent}"))

; --- network: loopback only, minus other local services
(deny network*)
(allow network-outbound (remote ip "localhost:*") (remote unix-socket))
(allow network-inbound (local ip "localhost:*") (local unix-socket))
(allow network-bind (local ip "localhost:*") (local unix-socket))
(deny network-outbound
{nl.join(f'  (remote ip "localhost:{p}")' for p in ports)})

; --- no automation of other apps, no signalling other processes
(deny appleevent-send)
(deny mach-lookup (global-name "com.apple.coreservices.appleevents"))
(deny signal (target others))
(allow signal (target children))
(deny process-exec
{nl.join(f'  (literal "{p}")' for p in no_exec)}
{nl.join(f'  (subpath "{p}")' for p in cua)})
""", len(ports)


def prepare(mode, lab, home=None):
    """(Re)generate the profile for `mode` into <lab>/run/. Returns its path."""
    home = str(home or Path.home())
    run = Path(lab) / "run"
    run.mkdir(exist_ok=True)
    path = run / f"sandbox-{mode}.sb"
    if mode == "guard":
        path.write_text(guard_profile(home))
    elif mode == "eval":
        text, _ = eval_profile(home, str(lab))
        path.write_text(text)
    else:
        raise ValueError(f"unknown sandbox mode '{mode}'")
    return path


def wrap(argv, mode, lab, home=None, refresh=False):
    path = Path(lab) / "run" / f"sandbox-{mode}.sb"
    if refresh or not path.exists():
        path = prepare(mode, lab, home)
    return ["sandbox-exec", "-f", str(path)] + list(argv)
