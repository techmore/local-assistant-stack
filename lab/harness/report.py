"""Build results/SUMMARY.md from results/*.json.

  .venv/bin/python harness/report.py [--base raw_think_off]

Statistics are deliberately modest: runs of the same task are not independent,
so confidence intervals come from a bootstrap over TASKS (not runs), and
differences between configs are paired per task.
"""
import argparse
import json
import random
import statistics as st
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tasks as tasks_mod  # noqa: E402

LAB = Path(__file__).resolve().parent.parent
RES = LAB / "results"
ORDER = ["raw_baseline", "raw_think_off", "raw_think_budget256", "raw_sampling_card", "raw_q8", "raw_narrow_tools",
         "raw_explicit_desc", "raw_constrained", "raw_rules", "raw_fewshot", "raw_verify", "raw_best", "raw_best_v2",
         "hermes_lab_bridge_think_off", "hermes_lab_best"]


def load():
    docs = {}
    for p in sorted(RES.glob("*.json")):
        d = json.loads(p.read_text())
        if "results" in d and "config" in d:
            docs[d["config"]["name"]] = d
    names = [n for n in ORDER if n in docs] + sorted(n for n in docs if n not in ORDER)
    return {n: docs[n] for n in names}


def rates(doc):
    return {r["id"]: r["pass_rate"] for r in doc["results"]}


def boot_ci(vals, n=4000, seed=7):
    rng = random.Random(seed)
    k = len(vals)
    means = sorted(sum(vals[rng.randrange(k)] for _ in range(k)) / k for _ in range(n))
    return means[int(0.025 * n)], means[int(0.975 * n)]


def med(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else None


def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def perf(doc):
    runs = [x for r in doc["results"] for x in r["runs"]]
    reqs = [q for x in runs for q in x["requests"]]
    first = [x["requests"][0] for x in runs if x["requests"]]
    big_prefill = [q["prompt_tps"] for q in reqs if (q.get("prompt_n") or 0) >= 200]
    return {
        "wall_med": med([x["wall_s"] for x in runs]),
        "wall_p90": sorted(x["wall_s"] for x in runs)[int(0.9 * len(runs))] if runs else None,
        "ttft_warm_med": med([q["ttft_s"] for q in first if (q.get("cache_n") or 0) > 0]),
        "prefill_tps": mean(big_prefill),
        "decode_tps": mean([q["decode_tps"] for q in reqs if (q.get("predicted_n") or 0) >= 20]),
        "prompt_tokens_first": med([q["prompt_tokens"] for q in first]),
        "completion_tokens_per_task": mean([sum((q.get("completion_tokens") or 0) for q in x["requests"]) for x in runs]),
        "requests_per_task": mean([len(x["requests"]) for x in runs]),
        "empty_responses": sum(x.get("empty_responses", 0) for x in runs),
        "malformed_args": sum(x.get("malformed_args", 0) for x in runs),
    }


def f(x, nd=1, suffix=""):
    return "-" if x is None else f"{x:.{nd}f}{suffix}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="raw_think_off", help="config the lever table is compared against")
    a = ap.parse_args()
    docs = load()
    if not docs:
        print("no results")
        return
    L = []
    L.append("# Results summary\n")
    L.append("Generated by `harness/report.py`. Pass rate = passed runs / total runs. The 95% interval is a bootstrap over tasks "
             "(runs of one task are correlated). With ~55 tasks, a difference of a few points between two configs is noise; "
             "see the paired column in the lever table.\n")

    # ---- overview
    L.append("## Overview\n")
    L.append("| config | level | runs | pass rate | 95% CI | always pass | flaky | always fail | median wall/task | p90 wall | decode tok/s | prefill tok/s | warm TTFT | first prompt tok | completion tok/task | server RSS peak |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for n, d in docs.items():
        r = list(rates(d).values())
        lo, hi = boot_ci(r)
        p = perf(d)
        total = sum(x["pass"] for row in d["results"] for x in row["runs"])
        nruns = sum(len(row["runs"]) for row in d["results"])
        star = " [shared GPU]" if d["config"].get("timing_caveat") else ""
        L.append(f"| {n}{star} | {d['config']['level']} | {len(r)}x{d['runs_per_task']} | **{100 * total / nruns:.1f}%** ({total}/{nruns}) | {100 * lo:.0f}-{100 * hi:.0f}% | "
                 f"{sum(v == 1 for v in r)} | {sum(0 < v < 1 for v in r)} | {sum(v == 0 for v in r)} | {f(p['wall_med'], 1, 's')} | {f(p['wall_p90'], 1, 's')} | "
                 f"{f(p['decode_tps'], 0)} | {f(p['prefill_tps'], 0)} | {f(p['ttft_warm_med'], 2, 's')} | {f(p['prompt_tokens_first'], 0)} | "
                 f"{f(p['completion_tokens_per_task'], 0)} | {d['server_memory'].get('rss_peak_sampled_mb', '-')} MB |")
    L.append("\n`[shared GPU]`: another model server was running on the same GPU during that run, so its wall times and tok/s are "
             "not comparable with the other rows (pass rates are unaffected). Server RSS grows with llama-server's host prompt "
             "cache (`--cache-ram`, default 8 GiB), so it reflects how many distinct prompts were cached, not model size.\n")

    # ---- per category
    L.append("## Pass rate by category (%)\n")
    cats = tasks_mod.CATEGORIES
    L.append("| config | " + " | ".join(cats) + " |")
    L.append("|---|" + "---|" * len(cats))
    for n, d in docs.items():
        cells = []
        for c in cats:
            rows = [r for r in d["results"] if r["cat"] == c]
            tot = sum(len(r["runs"]) for r in rows)
            cells.append(f"{100 * sum(x['pass'] for r in rows for x in r['runs']) / tot:.0f}" if tot else "-")
        L.append(f"| {n} | " + " | ".join(cells) + " |")
    L.append("\nTasks per category: " + ", ".join(f"{c} {sum(t['cat'] == c for t in tasks_mod.TASKS)}" for c in cats) + ".\n")

    # ---- levers vs base
    if a.base in docs:
        base = rates(docs[a.base])
        L.append(f"## Each config against `{a.base}` (paired by task)\n")
        L.append("| config | what changed | pass rate | delta vs base | 95% CI of delta | tasks better | tasks worse |")
        L.append("|---|---|---|---|---|---|---|")
        for n, d in docs.items():
            r = rates(d)
            common = [t for t in base if t in r]
            diffs = [r[t] - base[t] for t in common]
            lo, hi = boot_ci(diffs)
            verdict = "" if n == a.base else (" (clear)" if lo > 0 or hi < 0 else " (within noise)")
            L.append(f"| {n} | {d['config'].get('note', '')} | {100 * mean(list(r.values())):.1f}% | {100 * mean(diffs):+.1f} pts{verdict} | "
                     f"{100 * lo:+.0f} to {100 * hi:+.0f} | {sum(x > 0 for x in diffs)} | {sum(x < 0 for x in diffs)} |")
        L.append("")

    # ---- failure categories
    L.append("## Failure categories (failed runs)\n")
    allcats = sorted({x["fail_cat"] for d in docs.values() for r in d["results"] for x in r["runs"] if x["fail_cat"]})
    L.append("| config | " + " | ".join(allcats) + " | empty responses | malformed args |")
    L.append("|---|" + "---|" * (len(allcats) + 2))
    for n, d in docs.items():
        c = Counter(x["fail_cat"] for r in d["results"] for x in r["runs"] if x["fail_cat"])
        p = perf(d)
        L.append(f"| {n} | " + " | ".join(str(c.get(k, 0)) for k in allcats) + f" | {p['empty_responses']} | {p['malformed_args']} |")
    L.append("")

    # ---- per task matrix
    L.append("## Per-task passes (out of runs)\n")
    names = list(docs)
    L.append("| task | " + " | ".join(names) + " |")
    L.append("|---|" + "---|" * len(names))
    for t in tasks_mod.TASKS:
        cells = []
        for n in names:
            row = next((r for r in docs[n]["results"] if r["id"] == t["id"]), None)
            cells.append(f"{sum(x['pass'] for x in row['runs'])}/{len(row['runs'])}" if row else "-")
        L.append(f"| {t['id']} | " + " | ".join(cells) + " |")
    L.append("")
    (RES / "SUMMARY.md").write_text("\n".join(L))
    print(f"wrote {RES / 'SUMMARY.md'} ({len(docs)} configs)")


if __name__ == "__main__":
    main()
